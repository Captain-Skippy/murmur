import AppKit

/// Every item on a pasteboard with every type's data, so a paste-based insertion can put
/// the user's clipboard back exactly.
public struct PasteboardSnapshot: Sendable {
    public var items: [[(type: String, data: Data)]]
    public var changeCount: Int

    public init(items: [[(type: String, data: Data)]], changeCount: Int) {
        self.items = items
        self.changeCount = changeCount
    }

    public static func capture(_ pb: NSPasteboard) -> PasteboardSnapshot {
        let items = (pb.pasteboardItems ?? []).map { item in
            item.types.compactMap { t -> (type: String, data: Data)? in
                guard let d = item.data(forType: t) else { return nil }
                return (t.rawValue, d)
            }
        }
        return PasteboardSnapshot(items: items, changeCount: pb.changeCount)
    }

    /// Write the snapshot back. An empty snapshot clears the pasteboard.
    public func restore(to pb: NSPasteboard) {
        pb.clearContents()
        let objs: [NSPasteboardItem] = items.map { types in
            let it = NSPasteboardItem()
            for (t, d) in types { it.setData(d, forType: NSPasteboard.PasteboardType(t)) }
            return it
        }
        if !objs.isEmpty { pb.writeObjects(objs) }
    }
}

public enum PasteboardInsertion {
    /// Types that tell clipboard managers not to record the transient dictation text
    /// (nspasteboard.org conventions).
    public static let markerTypes = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    /// Write dictation text for a paste. Returns the change count that identifies our write.
    @discardableResult
    public static func write(_ text: String, to pb: NSPasteboard) -> Int {
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for m in markerTypes { item.setData(Data(), forType: NSPasteboard.PasteboardType(m)) }
        pb.writeObjects([item])
        return pb.changeCount
    }

    /// Restore only if nobody wrote to the pasteboard since our own write; if the user
    /// copied something in the meantime, that copy wins.
    @discardableResult
    public static func restoreIfUnchanged(_ snapshot: PasteboardSnapshot, ourChangeCount: Int, to pb: NSPasteboard) -> Bool {
        guard pb.changeCount == ourChangeCount else { return false }
        snapshot.restore(to: pb)
        return true
    }
}
